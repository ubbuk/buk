// Embeds dist/history_engine.wasm into lib/monitoring/history as a base64 TS
// module, so the module ships inside the server bundle (no file reads at runtime).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const wasm = readFileSync(path.join(here, "dist", "history_engine.wasm"));
const sha = createHash("sha256").update(wasm).digest("hex");
const out = path.join(here, "..", "..", "lib", "monitoring", "history", "history-engine.wasm.generated.ts");
writeFileSync(
  out,
  `// GENERATED by native/history-engine/embed.mjs -- do not edit by hand.\n` +
    `// Source: native/history-engine/history_engine.cpp (C++20, Emscripten).\n` +
    `export const HISTORY_ENGINE_WASM_SHA256 = "${sha}";\n` +
    `export const HISTORY_ENGINE_WASM_BASE64 =\n  "${wasm.toString("base64")}";\n`
);
console.log(`embedded ${wasm.length} bytes (sha256 ${sha.slice(0, 16)}…) -> ${path.relative(process.cwd(), out)}`);
