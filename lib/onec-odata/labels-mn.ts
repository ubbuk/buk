const hasOwn = (o: object, k: string) => Object.prototype.hasOwnProperty.call(o, k);

const KIND_PREFIX = /^(Catalog|DocumentJournal|Document|ChartOfAccounts|ChartOfCharacteristicTypes|ChartOfCalculationTypes|ExchangePlan|Constant|BusinessProcess|Task|(?:Information|Accumulation|Accounting|Calculation)Register)_(.+)$/;

/** Монгол нэр, эсвэл орчуулгагүй бол null (UI зөвхөн 1С-ийн жинхэнэ нэрийг харуулна) */
export function objectLabel(name: string): string | null {
  if (hasOwn(OBJECTS, name)) return OBJECTS[name];
  const m = KIND_PREFIX.exec(name);
  if (!m) return null;
  const inner = m[2];
  if (hasOwn(OBJECTS, inner)) return OBJECTS[inner];
  // Хүснэгтэн хэсэг, виртуал хүснэгт: <Эцэг>_<Дагавар>
  const i = inner.lastIndexOf("_");
  if (i <= 0) return null;
  const suffix = inner.slice(i + 1);
  const part = hasOwn(TABULAR_PARTS, suffix) ? TABULAR_PARTS[suffix] : hasOwn(VIRTUAL_TABLES, suffix) ? VIRTUAL_TABLES[suffix] : null;
  if (!part) return null;
  const parentInner = inner.slice(0, i);
  const parentFull = `${m[1]}_${parentInner}`;
  const parent = hasOwn(OBJECTS, parentFull) ? OBJECTS[parentFull] : hasOwn(OBJECTS, parentInner) ? OBJECTS[parentInner] : null;
  return parent ? `${parent} — ${part}` : null;
}

/** Талбарын монгол нэр: "Контрагент" -> "Харилцагч", "Контрагент_Key" -> "Харилцагч (ID)"; орчуулгагүй бол null */
export function fieldLabel(key: string): string | null {
  if (hasOwn(FIELDS, key)) return FIELDS[key];
  if (key.endsWith("_Key")) {
    const base = key.slice(0, -4);
    if (hasOwn(FIELDS, base)) return `${FIELDS[base]} (ID)`;
  }
  return null;
}

const TECHNICAL = /ДополнительныеРеквизиты|ДополнительныеСведения|ПрисоединенныеФайлы|ВерсииФайлов/;

/** Техникийн объект: UI-д «Техникийн» бүлэгт (анхдагчаар хаалттай) орно. Эрхэд нөлөөлөхгүй. */
export function isTechnicalObject(name: string): boolean {
  return name.startsWith("Constant_") || name.startsWith("ExchangePlan_") || name.endsWith("_RecordType") || TECHNICAL.test(name);
}

/** Хайлт: монгол нэр БА 1С-ийн жинхэнэ нэр хоёуланд нь (том жижиг үсэг үл ялгах) */
export function matchesSearch(name: string, needle: string): boolean {
  const n = needle.trim().toLowerCase();
  if (!n) return true;
  return name.toLowerCase().includes(n) || (objectLabel(name)?.toLowerCase().includes(n) ?? false);
}
