import { FIELDS, OBJECT_GROUPS, TABULAR_PARTS, VIRTUAL_TABLES } from "./labels-mn";

const table = (head: [string, string], rows: [string, string][]) =>
  [`| ${head[0]} | ${head[1]} |`, "| --- | --- |", ...rows.map(([a, b]) => `| \`${a}\` | ${b} |`)].join("\n");

